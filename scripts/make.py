#!/usr/bin/env python3
"""Build the Oak intro and insert it into a FireRed ROM - the same workflow as CFRU:

    python scripts/make.py            build, insert, write test.gba + offsets.ini
    python scripts/make.py find       print free-space offsets that fit the blob
    python scripts/make.py assets     only convert strings/graphics (no toolchain needed)
    python scripts/make.py check      re-read test.gba and verify the blob and every hook
    python scripts/clean.py [build]   remove build output

Edit the settings below, not the rest of the file.
"""
import os
import re
import shutil
import struct
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gfx      # noqa: E402
import insert   # noqa: E402
import strings  # noqa: E402

# ----------------------------------------------------------------------------- settings
OFFSET_TO_PUT = 0x900000      # where the code/data blob goes. Must be free space (0xFF).
SOURCE_ROM = 'BPRE0.gba'      # FireRed US 1.0 (or your CFRU build) - never modified
OUTPUT_ROM = 'test.gba'       # patched copy
PREFIX = 'arm-none-eabi-'     # toolchain prefix (devkitARM is found automatically)
OPT_LEVEL = '-O2'
FORCE = False                 # True: skip the "is this really BPRE 1.0 / a function start" hook checks
# ------------------------------------------------------------------------------------

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, 'build')
GEN = os.path.join(BUILD, 'gen')

CFLAGS = ['-mthumb', '-mno-thumb-interwork', '-mcpu=arm7tdmi', '-march=armv4t', '-mlong-calls',
          '-std=gnu11', OPT_LEVEL, '-Wall', '-Wextra', '-Wno-unused-parameter',
          '-Werror=implicit-function-declaration', '-Werror=int-conversion',
          '-Werror=incompatible-pointer-types',
          '-ffreestanding', '-fno-builtin', '-fno-pic', '-fno-strict-aliasing',
          '-fomit-frame-pointer', '-fno-tree-loop-distribute-patterns',
          '-I', 'include', '-I', os.path.join('build', 'gen')]
ASFLAGS = ['-mthumb', '-mcpu=arm7tdmi', '-march=armv4t', '-I', '.']


def fail(msg):
    print('error: ' + msg)
    sys.exit(1)


def find_tool(name):
    for prefix in (PREFIX, os.path.join(os.environ.get('DEVKITARM', ''), 'bin', PREFIX),
                   '/opt/devkitpro/devkitARM/bin/' + PREFIX, 'C:/devkitPro/devkitARM/bin/' + PREFIX):
        exe = shutil.which(prefix + name)
        if exe:
            return exe
    fail('could not find %s%s. Install an ARM toolchain (devkitARM or arm-none-eabi-gcc) '
         'or set PREFIX / DEVKITARM.' % (PREFIX, name))


def run(cmd):
    r = subprocess.run(cmd, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True)
    if r.stdout.strip():
        print(r.stdout.rstrip())
    if r.returncode:
        fail('command failed: ' + ' '.join(os.path.basename(c) for c in cmd[:1]) + ' ...')


def newer(target, sources):
    if not os.path.exists(target):
        return True
    t = os.path.getmtime(target)
    return any(os.path.exists(s) and os.path.getmtime(s) > t for s in sources)


def read_deps(dfile):
    if not os.path.exists(dfile):
        return []
    text = open(dfile).read().replace('\\\n', ' ')
    parts = text.split(':', 1)[-1].split()
    return [p if os.path.isabs(p) else os.path.join(ROOT, p) for p in parts]


def make_assets():
    try:
        names = strings.build(os.path.join(ROOT, 'strings'), GEN)
    except ValueError as e:
        fail(str(e))
    print('  str  %d strings' % len(names))
    try:
        gfx.build(os.path.join(ROOT, 'graphics'), BUILD, GEN)
    except ImportError:
        fail('Pillow is needed to convert graphics:  pip install pillow')
    except ValueError as e:
        fail(str(e))


def write_linker(offset):
    path = os.path.join(ROOT, 'linker.ld')
    text = ('/* Generated by scripts/make.py (OFFSET_TO_PUT = 0x%X) - do not edit */\n'
            'OUTPUT_ARCH(arm)\n\nMEMORY\n{\n    rom : ORIGIN = 0x%08X, LENGTH = 32M\n}\n\n'
            'SECTIONS\n{\n    .text : {\n        *(.text .text.*)\n        *(.rodata .rodata.*)\n'
            '        *(.data .data.*)\n        . = ALIGN(4);\n    } > rom\n\n'
            '    /DISCARD/ : { *(.ARM.attributes) *(.ARM.exidx*) *(.comment) *(.note*) *(.eh_frame*) '
            '*(.bss) *(COMMON) }\n}\n') % (offset, 0x08000000 + offset)
    if not os.path.exists(path) or open(path).read() != text:
        with open(path, 'w', newline='\n') as f:
            f.write(text)
    return path


def compile_all():
    cc, asm, ld = find_tool('gcc'), find_tool('as'), find_tool('ld')
    objs = []
    for sub, ext in (('src', '.c'), ('assembly', '.s'), (os.path.join('build', 'gen'), '.s')):
        d = os.path.join(ROOT, sub)
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if not fn.endswith(ext):
                continue
            src = os.path.join(sub, fn)
            obj = os.path.join('build', 'obj', sub.replace(os.sep, '_'), fn[:-len(ext)] + '.o')
            full_obj = os.path.join(ROOT, obj)
            os.makedirs(os.path.dirname(full_obj), exist_ok=True)
            objs.append(obj)
            dfile = full_obj[:-2] + '.d'
            deps = [os.path.join(ROOT, src)] + read_deps(dfile)
            # generated assembly pulls in binary files via .incbin
            if ext == '.s' and sub.endswith('gen'):
                deps += [os.path.join(BUILD, 'graphics', f) for f in os.listdir(os.path.join(BUILD, 'graphics'))] \
                    if os.path.isdir(os.path.join(BUILD, 'graphics')) else []
            if not newer(full_obj, deps):
                continue
            if ext == '.c':
                print('  cc   ' + src)
                run([cc] + CFLAGS + ['-MMD', '-MP', '-MF', obj[:-2] + '.d', '-c', src, '-o', obj])
            else:
                print('  as   ' + src)
                run([asm] + ASFLAGS + [src, '-o', obj])
    elf = os.path.join('build', 'oak_intro.elf')
    ldfile = os.path.relpath(write_linker(OFFSET_TO_PUT), ROOT)
    if any(newer(os.path.join(ROOT, elf), [os.path.join(ROOT, o) for o in objs] + [os.path.join(ROOT, 'BPRE.ld'), os.path.join(ROOT, ldfile)])
           for _ in [0]):
        print('  ld   ' + elf)
        run([ld, '-T', ldfile, '-T', 'BPRE.ld', '-o', elf] + objs)
    binfile = os.path.join('build', 'oak_intro.bin')
    run([find_tool('objcopy'), '-O', 'binary', elf, binfile])
    return os.path.join(ROOT, elf), os.path.join(ROOT, binfile)


def read_symbols(elf):
    out = subprocess.run([find_tool('nm'), '-g', '--defined-only', elf], stdout=subprocess.PIPE,
                         universal_newlines=True).stdout
    syms = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in ('T', 't', 'D', 'R', 'B'):
            addr = int(parts[0], 16)
            if parts[1] in ('T', 't'):
                addr |= 1  # every function here is Thumb
            syms[parts[2]] = addr
    return syms


def main(argv):
    mode = argv[0] if argv else 'build'
    t0 = time.time()
    if mode == 'assets':
        make_assets()
        return
    if mode == 'check':
        ini = os.path.join(ROOT, 'offsets.ini')
        if not os.path.exists(ini):
            fail('offsets.ini not found - run python scripts/make.py first')
        syms = {}
        for line in open(ini):
            if '=' in line:
                k, v = line.strip().split('=')
                syms[k] = int(v, 16)
        ok = insert.verify(os.path.join(ROOT, OUTPUT_ROM), os.path.join(BUILD, 'oak_intro.bin'),
                           OFFSET_TO_PUT, os.path.join(ROOT, 'hooks'), syms)
        sys.exit(0 if ok else 1)
    rom = os.path.join(ROOT, SOURCE_ROM)
    if not os.path.exists(rom):
        fail('%s not found. Put your FireRed ROM in %s (or change SOURCE_ROM).' % (SOURCE_ROM, ROOT))
    make_assets()
    elf, binfile = compile_all()
    size = os.path.getsize(binfile)
    if mode == 'find':
        for off in insert.find_free(rom, size):
            print('  free: 0x%X' % off)
        return
    print('  blob %d bytes at 0x%08X' % (size, 0x08000000 + OFFSET_TO_PUT))
    syms = read_symbols(elf)
    insert.insert(rom, binfile, OFFSET_TO_PUT, os.path.join(ROOT, OUTPUT_ROM),
                  os.path.join(ROOT, 'hooks'), os.path.join(ROOT, 'bytereplacement'), syms, FORCE)
    with open(os.path.join(ROOT, 'offsets.ini'), 'w', newline='\n') as f:
        for name in sorted(syms):
            if not name.startswith('gGfx_') and not name.startswith('gText_'):
                f.write('%s=%08X\n' % (name, syms[name]))
        for name in sorted(syms):
            if name.startswith('gText_') or name.startswith('gGfx_'):
                f.write('%s=%08X\n' % (name, syms[name]))
    print('done in %.1fs -> %s, offsets.ini' % (time.time() - t0, OUTPUT_ROM))


if __name__ == '__main__':
    main(sys.argv[1:])
