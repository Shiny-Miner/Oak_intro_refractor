#!/usr/bin/env python3
"""Compile strings/*.string into Pokemon-encoded assembly + a C header.

File format (one string per line, blank lines and '#' comments ignored):

    gText_Hello: Hello there!\\nIt's so very nice to meet you!\\p

Escapes:  \\n line break   \\l scroll line   \\p new page
Tokens:   {PLAYER} {RIVAL} {STR_VAR_1..3}  or raw bytes  {0xNN}
          [PK] [MN] [...] [m] [f] etc. are NOT needed: type the real character
          (e, ..., male/female signs) and it is mapped for you.

Every label becomes `const u8 <label>[]` (declared in the generated strings.h).
"""
import os
import re
import sys

CHARMAP = {' ': 0x00}
for i, c in enumerate('ÀÁÂÇÈÉÊËÌ'):
    CHARMAP[c] = 0x01 + i
CHARMAP.update({'Î': 0x0B, 'Ï': 0x0C, 'Ò': 0x0D, 'Ó': 0x0E, 'Ô': 0x0F, 'Æ': 0x10, 'Ù': 0x11,
                'Ú': 0x12, 'Û': 0x13, 'Ñ': 0x14, 'ß': 0x15, 'à': 0x16, 'á': 0x17, 'ç': 0x19,
                'è': 0x1A, 'é': 0x1B, 'ê': 0x1C, 'ë': 0x1D, 'ì': 0x1E, 'î': 0x20, 'ï': 0x21,
                'ò': 0x22, 'ó': 0x23, 'ô': 0x24, 'æ': 0x25, 'ù': 0x26, 'û': 0x28, 'ñ': 0x29,
                'º': 0x2A, 'ª': 0x2B, '&': 0x2D, '+': 0x2E, '=': 0x35, ';': 0x36, '¿': 0x51,
                '¡': 0x52, '%': 0x5B, '(': 0x5C, ')': 0x5D, 'â': 0x68, 'í': 0x6F,
                '0': 0xA1, '1': 0xA2, '2': 0xA3, '3': 0xA4, '4': 0xA5, '5': 0xA6, '6': 0xA7,
                '7': 0xA8, '8': 0xA9, '9': 0xAA, '!': 0xAB, '?': 0xAC, '.': 0xAD, '-': 0xAE,
                '·': 0xAF, '…': 0xB0, '“': 0xB1, '”': 0xB2, '‘': 0xB3, "'": 0xB4, '’': 0xB4,
                '♂': 0xB5, '♀': 0xB6, '$': 0xB7, ',': 0xB8, '×': 0xB9, '/': 0xBA,
                ':': 0xF0, 'Ö': 0xF1, 'Ü': 0xF3, 'ö': 0xF5, 'ü': 0xF6, '>': 0xEF})
for i, c in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
    CHARMAP[c] = 0xBB + i
for i, c in enumerate('abcdefghijklmnopqrstuvwxyz'):
    CHARMAP[c] = 0xD5 + i

ESCAPES = {'n': 0xFE, 'l': 0xFA, 'p': 0xFB}
TOKENS = {'PLAYER': [0xFD, 0x01], 'STR_VAR_1': [0xFD, 0x02], 'STR_VAR_2': [0xFD, 0x03],
          'STR_VAR_3': [0xFD, 0x04], 'KUN': [0xFD, 0x05], 'RIVAL': [0xFD, 0x06]}
EOS = 0xFF


def encode(text, where):
    out = []
    i = 0
    prev_space = True
    while i < len(text):
        c = text[i]
        if c == '\\':
            i += 1
            if i >= len(text):
                raise ValueError('%s: dangling backslash' % where)
            e = text[i]
            if e in ESCAPES:
                out.append(ESCAPES[e])
            else:
                raise ValueError('%s: unknown escape \\%s' % (where, e))
        elif c == '{':
            j = text.find('}', i)
            if j < 0:
                raise ValueError('%s: unterminated {' % where)
            tok = text[i + 1:j]
            if tok in TOKENS:
                out.extend(TOKENS[tok])
            elif re.fullmatch(r'0x[0-9A-Fa-f]{1,2}', tok):
                out.append(int(tok, 16))
            else:
                raise ValueError('%s: unknown token {%s}' % (where, tok))
            i = j
        elif c == '"':
            out.append(0xB1 if prev_space else 0xB2)
        elif c in CHARMAP:
            out.append(CHARMAP[c])
        else:
            raise ValueError('%s: character %r is not in the Pokemon charmap' % (where, c))
        prev_space = c in ' \n'
        i += 1
    out.append(EOS)
    return out


def parse(path):
    entries = []
    with open(path, encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\r\n')
            if not line.strip() or line.lstrip().startswith('#'):
                continue
            m = re.match(r'^\s*([A-Za-z_]\w*)\s*:\s?(.*)$', line)
            if not m:
                raise ValueError('%s:%d: expected "label: text"' % (path, n))
            entries.append((m.group(1), encode(m.group(2), '%s:%d' % (path, n))))
    return entries


def build(src_dir, gen_dir):
    """Returns the list of labels written. Raises ValueError on bad input."""
    files = sorted(f for f in os.listdir(src_dir) if f.endswith('.string')) if os.path.isdir(src_dir) else []
    seen = {}
    asm = ['@ Generated by scripts/strings.py - do not edit', '.section .rodata', '.align 2', '']
    hdr = ['/* Generated by scripts/strings.py - do not edit */', '#ifndef GUARD_GEN_STRINGS_H',
           '#define GUARD_GEN_STRINGS_H', '', '#include "types.h"', '']
    for fn in files:
        for label, data in parse(os.path.join(src_dir, fn)):
            if label in seen:
                raise ValueError('%s: label %s already defined in %s' % (fn, label, seen[label]))
            seen[label] = fn
            asm.append('.global %s' % label)
            asm.append('%s:' % label)
            asm.append('\t.byte ' + ', '.join('0x%02X' % b for b in data))
            asm.append('.align 2')
            hdr.append('extern const u8 %s[];' % label)
    hdr += ['', '#endif', '']
    os.makedirs(gen_dir, exist_ok=True)
    with open(os.path.join(gen_dir, 'strings.s'), 'w', newline='\n') as f:
        f.write('\n'.join(asm) + '\n')
    with open(os.path.join(gen_dir, 'strings.h'), 'w', newline='\n') as f:
        f.write('\n'.join(hdr))
    return list(seen)


if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    names = build(os.path.join(root, 'strings'), os.path.join(root, 'build', 'gen'))
    print('%d strings' % len(names))
